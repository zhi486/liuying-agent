-- 只保存派发意图与结果摘要；参数正文、结果正文和第三方密钥均不入库。
CREATE TABLE IF NOT EXISTS agent_mcp_invocations (
  id TEXT PRIMARY KEY NOT NULL CHECK (length(id) = 36),
  owner_id TEXT NOT NULL REFERENCES agent_budget_accounts(owner_id),
  device_id TEXT NOT NULL,
  task_id TEXT NOT NULL REFERENCES agent_cloud_tasks(id),
  execution_hash TEXT NOT NULL CHECK (length(execution_hash) = 64),
  call_id TEXT NOT NULL CHECK (length(call_id) BETWEEN 1 AND 80),
  service_id TEXT NOT NULL CHECK (length(service_id) = 36),
  endpoint TEXT NOT NULL CHECK (length(endpoint) <= 2048),
  service_revision TEXT NOT NULL CHECK (length(service_revision) = 36),
  catalog_fingerprint TEXT NOT NULL CHECK (length(catalog_fingerprint) = 64),
  model_name TEXT NOT NULL CHECK (length(model_name) <= 48),
  tool_name TEXT NOT NULL CHECK (length(tool_name) BETWEEN 1 AND 128),
  mode TEXT NOT NULL CHECK (mode IN ('read','confirm')),
  arguments_digest TEXT NOT NULL CHECK (length(arguments_digest) = 64),
  intent_digest TEXT NOT NULL CHECK (length(intent_digest) = 64),
  status TEXT NOT NULL CHECK (status IN ('pending','approved','denied','may_have_dispatched','completed')),
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL CHECK (expires_at > created_at AND expires_at <= created_at + 30000),
  confirmed_at INTEGER,
  dispatched_at INTEGER,
  result_digest TEXT CHECK (result_digest IS NULL OR length(result_digest) = 64),
  result_is_error INTEGER CHECK (result_is_error IS NULL OR result_is_error IN (0,1)),
  FOREIGN KEY (device_id, owner_id) REFERENCES agent_devices(id, owner_id),
  UNIQUE (task_id, call_id),
  UNIQUE (task_id, service_id, tool_name, arguments_digest),
  CHECK (status != 'pending' OR (mode = 'confirm' AND confirmed_at IS NULL)),
  CHECK (mode != 'confirm' OR status NOT IN ('approved','may_have_dispatched','completed') OR confirmed_at IS NOT NULL),
  CHECK (confirmed_at IS NULL OR (confirmed_at >= created_at AND confirmed_at < expires_at)),
  CHECK ((status IN ('may_have_dispatched','completed')) = (dispatched_at IS NOT NULL)),
  CHECK (dispatched_at IS NULL OR (dispatched_at >= created_at AND dispatched_at < expires_at)),
  CHECK ((status = 'completed') = (result_digest IS NOT NULL)),
  CHECK ((status = 'completed') = (result_is_error IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS agent_mcp_invocation_device ON agent_mcp_invocations(owner_id, device_id, id);
